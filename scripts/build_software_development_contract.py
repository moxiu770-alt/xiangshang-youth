def set_cell_shading(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_margins(cell, top=80, start=120, bottom=80, end=120):
    tc_pr = cell._tc.get_or_add_tcPr()
    mar = tc_pr.first_child_found_in("w:tcMar")
    if mar is None:
        mar = OxmlElement("w:tcMar")
        tc_pr.append(mar)
    for side, value in (("top", top), ("start", start), ("bottom", bottom), ("end", end)):
        node = mar.find(qn(f"w:{side}"))
        if node is None:
            node = OxmlElement(f"w:{side}")
            mar.append(node)
        node.set(qn("w:w"), str(value))
        node.set(qn("w:type"), "dxa")


def set_cell_border(cell, **kwargs):
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = tc_pr.first_child_found_in("w:tcBorders")
    if borders is None:
        borders = OxmlElement("w:tcBorders")
        tc_pr.append(borders)
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        if edge not in kwargs:
            continue
        spec = kwargs[edge]
        tag = qn(f"w:{edge}")
        node = borders.find(tag)
        if node is None:
            node = OxmlElement(f"w:{edge}")
            borders.append(node)
        for key, value in spec.items():
            node.set(qn(f"w:{key}"), str(value))


def set_table_widths(table, widths_dxa):
    # A4 page with 2.8 cm side margins: retain a small right-side allowance.
    if sum(widths_dxa) != TABLE_WIDTH_DXA:
        original_total = sum(widths_dxa)
        scaled = [round(width * TABLE_WIDTH_DXA / original_total) for width in widths_dxa]
        scaled[-1] += TABLE_WIDTH_DXA - sum(scaled)
        widths_dxa = scaled
    tbl_pr = table._tbl.tblPr
    tbl_w = tbl_pr.first_child_found_in("w:tblW")
    if tbl_w is None:
        tbl_w = OxmlElement("w:tblW")
        tbl_pr.append(tbl_w)
    tbl_w.set(qn("w:w"), str(sum(widths_dxa)))
    tbl_w.set(qn("w:type"), "dxa")
    ind = tbl_pr.first_child_found_in("w:tblInd")
    if ind is None:
        ind = OxmlElement("w:tblInd")
        tbl_pr.append(ind)
    ind.set(qn("w:w"), "120")
    ind.set(qn("w:type"), "dxa")
    layout = tbl_pr.first_child_found_in("w:tblLayout")
    if layout is None:
        layout = OxmlElement("w:tblLayout")
        tbl_pr.append(layout)
    layout.set(qn("w:type"), "fixed")
    grid = table._tbl.tblGrid
    for gc in list(grid):
        grid.remove(gc)
    for width in widths_dxa:
        gc = OxmlElement("w:gridCol")
        gc.set(qn("w:w"), str(width))
        grid.append(gc)
    for row in table.rows:
        for i, cell in enumerate(row.cells):
            tc_pr = cell._tc.get_or_add_tcPr()
            tc_w = tc_pr.first_child_found_in("w:tcW")
            if tc_w is None:
                tc_w = OxmlElement("w:tcW")
                tc_pr.append(tc_w)
            tc_w.set(qn("w:w"), str(widths_dxa[i]))
            tc_w.set(qn("w:type"), "dxa")


def set_repeat_table_header(row):
    tr_pr = row._tr.get_or_add_trPr()
    node = OxmlElement("w:tblHeader")
    node.set(qn("w:val"), "true")
    tr_pr.append(node)


def set_keep_with_next(paragraph):
    p_pr = paragraph._p.get_or_add_pPr()
    node = OxmlElement("w:keepNext")
    p_pr.append(node)


def set_paragraph_border_bottom(paragraph, color=BLUE, size="12", space="7"):
    p_pr = paragraph._p.get_or_add_pPr()
    p_bdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), size)
    bottom.set(qn("w:space"), space)
    bottom.set(qn("w:color"), color)
    p_bdr.append(bottom)
    p_pr.append(p_bdr)


def set_run(run, size=10.5, bold=False, color=INK, name=FONT):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:ascii"), name)
    run._element.rPr.rFonts.set(qn("w:hAnsi"), name)
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.font.color.rgb = RGBColor.from_string(color)
    run.bold = bold


def style_para(p, before=0, after=6, line=1.5, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_indent=True):
    fmt = p.paragraph_format
    fmt.space_before = Pt(before)
    fmt.space_after = Pt(after)
    fmt.line_spacing = line
    fmt.alignment = align
    fmt.first_line_indent = Cm(0.74) if first_indent else None


def add_body(doc, text, before=0, after=6, indent=True):
    p = doc.add_paragraph()
    style_para(p, before, after, 1.5, WD_ALIGN_PARAGRAPH.JUSTIFY, indent)
    set_run(p.add_run(text), size=12)
    return p


def add_clause(doc, no, title, text):
    p = doc.add_paragraph()
    style_para(p, before=12, after=6, line=1.35, align=WD_ALIGN_PARAGRAPH.LEFT, first_indent=False)
    set_keep_with_next(p)
    r = p.add_run(f"第{no}条  {title}")
    set_run(r, size=14, bold=True, color=BLUE, name=SANS)
    add_body(doc, text)


def add_subclause(doc, no, text):
    p = doc.add_paragraph()
    style_para(p, before=0, after=5, line=1.5, align=WD_ALIGN_PARAGRAPH.JUSTIFY, first_indent=False)
    p.paragraph_format.left_indent = Cm(0.74)
    p.paragraph_format.first_line_indent = Cm(-0.74)
    set_run(p.add_run(f"{no}  {text}"), size=12)
    return p


def set_table_font(table, header=True, size=9.5):
    for ri, row in enumerate(table.rows):
        for cell in row.cells:
            cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
            set_cell_margins(cell)
            set_cell_border(cell, top={"val": "single", "sz": "6", "color": "000000"}, bottom={"val": "single", "sz": "6", "color": "000000"}, left={"val": "single", "sz": "6", "color": "000000"}, right={"val": "single", "sz": "6", "color": "000000"})
            for p in cell.paragraphs:
                p.paragraph_format.space_before = Pt(0)
                p.paragraph_format.space_after = Pt(2)
                p.paragraph_format.line_spacing = 1.2
                p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                for run in p.runs:
                    set_run(run, size=size, bold=(header and ri == 0), color=INK, name=SANS if header and ri == 0 else FONT)
            if header and ri == 0:
                set_cell_shading(cell, LIGHT_GRAY)


def add_table(doc, headers, rows, widths, font_size=9.2):
    table = doc.add_table(rows=1, cols=len(headers))
    table.alignment = WD_TABLE_ALIGNMENT.LEFT
    table.autofit = False
    for c, val in zip(table.rows[0].cells, headers):
        c.text = val
    for data in rows:
        cells = table.add_row().cells
        for c, val in zip(cells, data):
            c.text = val
    set_table_widths(table, widths)
    set_repeat_table_header(table.rows[0])
    set_table_font(table, True, font_size)
    return table


def add_field(paragraph, field):
    run = paragraph.add_run()
    fld_char1 = OxmlElement("w:fldChar")
    fld_char1.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = field
    fld_char2 = OxmlElement("w:fldChar")
    fld_char2.set(qn("w:fldCharType"), "end")
    run._r.append(fld_char1)
    run._r.append(instr)
    run._r.append(fld_char2)


